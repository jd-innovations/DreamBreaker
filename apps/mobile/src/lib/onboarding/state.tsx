type OnboardingContextValue = {
  draft: OnboardingDraft;
  update: <K extends keyof OnboardingDraft>(key: K, value: OnboardingDraft[K]) => void;
  toggleInList: (key: 'playingStyle' | 'availability' | 'intent', value: string, max?: number) => void;
  reset: () => void;
};

const OnboardingContext = createContext<OnboardingContextValue | null>(null);

export function OnboardingProvider({ children }: { children: React.ReactNode }) {
  const [draft, setDraft] = useState<OnboardingDraft>(INITIAL_DRAFT);

  const update = useCallback(<K extends keyof OnboardingDraft>(key: K, value: OnboardingDraft[K]) => {
    setDraft(prev => ({ ...prev, [key]: value }));
  }, []);

  const toggleInList = useCallback((key: 'playingStyle' | 'availability' | 'intent', value: string, max?: number) => {
    setDraft(prev => {
      const current = prev[key];
      const has = current.includes(value);
      if (has) return { ...prev, [key]: current.filter(v => v !== value) };
      if (max != null && current.length >= max) return prev; // at cap ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ignore new selections
      return { ...prev, [key]: [...current, value] };
    });
  }, []);

  const reset = useCallback(() => setDraft(INITIAL_DRAFT), []);

  const value = useMemo(() => ({ draft, update, toggleInList, reset }), [draft, update, toggleInList, reset]);

  return <OnboardingContext.Provider value={value}>{children}</OnboardingContext.Provider>;
}

export function useOnboarding(): OnboardingContextValue {
  const ctx = useContext(OnboardingContext);
  if (!ctx) throw new Error('useOnboarding must be used within OnboardingProvider');
  return ctx;
}
